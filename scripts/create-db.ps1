<#
.SYNOPSIS
  Creates the PostgreSQL database and role for MzaziCare and writes backend\.env.

.DESCRIPTION
  Asks for the PostgreSQL admin ("postgres") password. That password is used for this one run only: it is
  typed without echo, never written to disk, and never put in backend\.env. The app gets its own role with a
  randomly generated password instead.

  Refuses to overwrite an existing backend\.env unless -Force is given.
#>
param([switch]$Force, [string]$AdminUser = 'postgres', [string]$DbHost = 'localhost', [int]$Port = 5432)

. "$PSScriptRoot\_common.ps1"

$envFile = Join-Path $Root 'backend\.env'
if ((Test-Path $envFile) -and -not $Force) { Fail 'backend\.env already exists. Use -Force to replace it (a new database password will be generated).' }
if (-not (Test-Path $Py)) { Fail 'Run scripts\setup.ps1 first.' }
$psql = Find-Psql
if (-not $psql) { Fail 'psql was not found. Install PostgreSQL and try again.' }

$dbName = 'mzazicare'
$dbUser = 'mzazicare'
$secure = Read-Host "Password for PostgreSQL user '$AdminUser' (not stored)" -AsSecureString
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
$env:PGPASSWORD = [Runtime.InteropServices.Marshal]::PtrToStringAuto($bstr)
[Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)

try {
    $appPassword = New-RandomString 24
    $secretKey = New-RandomString 60
    $common = @('-U', $AdminUser, '-h', $DbHost, '-p', "$Port", '-w', '-v', 'ON_ERROR_STOP=1', '-tA')

    Step 'Connecting to PostgreSQL'
    Run $psql ($common + @('-c', 'select 1;')) | Out-Null
    Ok 'connected'

    Step "Creating role '$dbUser' and database '$dbName'"
    $roleExists = & $psql ($common + @('-c', "select 1 from pg_roles where rolname='$dbUser'"))
    if ($roleExists -eq '1') {
        Run $psql ($common + @('-c', "ALTER ROLE $dbUser WITH LOGIN PASSWORD '$appPassword'"))
        Ok 'role existed: password rotated'
    } else {
        Run $psql ($common + @('-c', "CREATE ROLE $dbUser LOGIN PASSWORD '$appPassword'"))
        Ok 'role created'
    }
    $dbExists = & $psql ($common + @('-c', "select 1 from pg_database where datname='$dbName'"))
    if ($dbExists -ne '1') {
        Run $psql ($common + @('-c', "CREATE DATABASE $dbName OWNER $dbUser"))
        Ok 'database created'
    } else { Ok 'database already exists' }
} finally {
    Remove-Item Env:PGPASSWORD -ErrorAction SilentlyContinue
}

Step 'Writing backend\.env'
$lines = @(
    '# Generated by scripts\create-db.ps1. Git-ignored. Never commit this file.',
    "DJANGO_SECRET_KEY=$secretKey",
    'DJANGO_DEBUG=1',
    'DJANGO_ALLOWED_HOSTS=*',
    "DB_NAME=$dbName",
    "DB_USER=$dbUser",
    "DB_PASSWORD=$appPassword",
    "DB_HOST=$DbHost",
    "DB_PORT=$Port"
)
[IO.File]::WriteAllText($envFile, (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding($false)))
Ok 'backend\.env written'

Step 'Applying database migrations'
Push-Location (Join-Path $Root 'backend')
try { Run $Py @('manage.py', 'migrate') } finally { Pop-Location }
Ok 'database is ready'
