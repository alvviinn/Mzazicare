export type IconName = keyof typeof SET;

export function Icon({ name, size = icon.s, color = colors.ink }: { name: IconName; size?: number; color?: string }) {
  const Glyph = SET[name];
  return <Glyph size={size} color={color} strokeWidth={icon.stroke} absoluteStrokeWidth />;
}

